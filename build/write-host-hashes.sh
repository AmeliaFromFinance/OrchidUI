#!/usr/bin/env bash
# Writes src/OrchidUI/Session/HostHashes.g.cs with the SHA-256 of each orchid-host binary given.
# The release workflow runs this on the hosts it just published (after signing), then builds the DLL.
#   build/write-host-hashes.sh dist/win-x64/orchid-host.exe dist/linux-x64/orchid-host ...
set -euo pipefail
[ $# -gt 0 ] || { echo "usage: $0 <orchid-host binary>..." >&2; exit 64; }
out="$(dirname "$0")/../src/OrchidUI/Session/HostHashes.g.cs"
hash() { if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }
{
  echo '// <auto-generated>'
  echo '//   SHA-256 of every orchid-host build this OrchidUI.dll trusts. The release workflow regenerates'
  echo '//   this file from the hosts it just published, then builds the DLL. An empty list means a'
  echo '//   development build: the host is started without a check and the log says so.'
  echo '// </auto-generated>'
  echo 'namespace OrchidUI'
  echo '{'
  echo '    internal static class HostHashes'
  echo '    {'
  echo '        public static readonly string[] Known ='
  echo '        {'
  for f in "$@"; do
    [ -f "$f" ] || { echo "not a file: $f" >&2; exit 66; }
    echo "            \"$(hash "$f")\", // $(basename "$(dirname "$f")")/$(basename "$f")"
  done
  echo '        };'
  echo '    }'
  echo '}'
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "Wrote $# hash(es) to $out"
